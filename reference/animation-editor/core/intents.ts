const directIntent = ({
  id,
  group,
  title,
  description,
  supportedTargetTypes = [...ALL_VISUAL],
  allowedTriggers = ["in-view", "page-load"],
  repetition = "once",
}: {
  id: DirectPresetId;
  group: AnimationIntentDefinition["group"];
  title: string;
  description: string;
  supportedTargetTypes?: AnimationTargetType[];
  allowedTriggers?: AnimationIntentDefinition["allowedTriggers"];
  repetition?: AnimationIntentDefinition["defaults"]["repetition"];
}): AnimationIntentDefinition => ({
  id,
  group,
  title,
  description,
  supportedTargetTypes,
  allowedTriggers,
  defaults: {
    strength: "balanced",
    speed: repetition === "continuous" ? "slow" : "normal",
    delay: "none",
    trigger: allowedTriggers[0] ?? "in-view",
    repetition,
  },
});

